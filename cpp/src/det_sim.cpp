Api load_all() {
  Api a;
  void* drv = open_lib(kDriver);
  if (!drv) { a.error = std::string("CUDA driver library not found (") + kDriver + ")"; return a; }
#ifndef _WIN32
  // NVRTC dlopens libnvrtc-builtins.so.<ver> by soname; preload it from the executable directory
  // (not on the library path) so that lookup resolves to the already-loaded copy.
  {
    std::error_code ec;
    for (const auto& e : std::filesystem::directory_iterator(exe_dir(), ec))
      if (e.path().filename().string().rfind("libnvrtc-builtins.so.", 0) == 0) dlopen(e.path().c_str(), RTLD_NOW | RTLD_GLOBAL);
  }
#endif
  void* rt = open_lib((exe_dir() / kNvrtc).string());
  if (!rt) rt = open_lib(kNvrtc);
  if (!rt) { a.error = std::string("NVRTC library not found (") + kNvrtc + " next to the executable or on the library path)"; return a; }
  bool ok = true;
  auto need = [&](void* lib, auto& fp, const char* name) { fp = reinterpret_cast<std::remove_reference_t<decltype(fp)>>(sym(lib, name)); if (!fp) { ok = false; a.error += std::string(" missing ") + name; } };
  need(drv, a.cuInit, "cuInit"); need(drv, a.cuDeviceGet, "cuDeviceGet"); need(drv, a.cuDeviceGetName, "cuDeviceGetName");
  need(drv, a.cuDeviceGetAttribute, "cuDeviceGetAttribute"); need(drv, a.cuDevicePrimaryCtxRetain, "cuDevicePrimaryCtxRetain");
  need(drv, a.cuDevicePrimaryCtxRelease, "cuDevicePrimaryCtxRelease_v2"); need(drv, a.cuCtxSetCurrent, "cuCtxSetCurrent");
  need(drv, a.cuCtxSynchronize, "cuCtxSynchronize"); need(drv, a.cuModuleLoadData, "cuModuleLoadData");
  need(drv, a.cuModuleUnload, "cuModuleUnload"); need(drv, a.cuModuleGetFunction, "cuModuleGetFunction");
  need(drv, a.cuMemAlloc, "cuMemAlloc_v2"); need(drv, a.cuMemFree, "cuMemFree_v2");
  need(drv, a.cuMemcpyHtoD, "cuMemcpyHtoD_v2"); need(drv, a.cuMemcpyDtoH, "cuMemcpyDtoH_v2");
  need(drv, a.cuLaunchKernel, "cuLaunchKernel"); need(drv, a.cuGetErrorString, "cuGetErrorString");
  need(rt, a.nvrtcVersion, "nvrtcVersion"); need(rt, a.nvrtcGetNumSupportedArchs, "nvrtcGetNumSupportedArchs");
  need(rt, a.nvrtcGetSupportedArchs, "nvrtcGetSupportedArchs"); need(rt, a.nvrtcCreateProgram, "nvrtcCreateProgram");
  need(rt, a.nvrtcDestroyProgram, "nvrtcDestroyProgram"); need(rt, a.nvrtcCompileProgram, "nvrtcCompileProgram");
  need(rt, a.nvrtcGetProgramLogSize, "nvrtcGetProgramLogSize"); need(rt, a.nvrtcGetProgramLog, "nvrtcGetProgramLog");
  need(rt, a.nvrtcGetCUBINSize, "nvrtcGetCUBINSize"); need(rt, a.nvrtcGetCUBIN, "nvrtcGetCUBIN");
  need(rt, a.nvrtcGetPTXSize, "nvrtcGetPTXSize"); need(rt, a.nvrtcGetPTX, "nvrtcGetPTX");
  need(rt, a.nvrtcGetErrorString, "nvrtcGetErrorString");
  a.ok = ok;
  if (!ok) a.error = "CUDA/NVRTC symbol lookup failed:" + a.error;
  return a;
}
