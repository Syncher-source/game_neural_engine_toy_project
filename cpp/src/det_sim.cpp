struct DetSim::Impl {
  Dims d{};
  std::vector<float> blob;                 // transposed layout, see det_math.h
  std::vector<float> xs, h, a, g, y;       // CPU scratch
  DetSim::Backend backend = DetSim::Backend::Cpu;
  // cuda
  cu::CUcontext ctx = nullptr;
  cu::CUmodule mod = nullptr;
  cu::CUfunction fn = nullptr;
  cu::CUdeviceptr d_w = 0, d_x = 0, d_y = 0;
  cu::CUdevice dev = 0;
  std::string device_name;

  size_t off_s_mean() const { return NGE_DET_OFF_S_MEAN(d.S, d.M, d.H, d.O); }
  size_t off_s_std() const { return NGE_DET_OFF_S_STD(d.S, d.M, d.H, d.O); }
  size_t off_inp_w() const { return NGE_DET_OFF_INP_W(d.S, d.M, d.H, d.O); }
  size_t off_inp_b() const { return NGE_DET_OFF_INP_B(d.S, d.M, d.H, d.O); }
  size_t off_layer(int l) const { return NGE_DET_OFF_LAYER(d.S, d.M, d.H, d.O, l); }
  size_t off_out_w() const { return NGE_DET_OFF_OUT_W(d.S, d.M, d.H, d.O, d.L); }
  size_t off_out_b() const { return NGE_DET_OFF_OUT_B(d.S, d.M, d.H, d.O, d.L); }
  const float* d_std() const { return blob.data() + off_out_b() + d.O; }      // appended after the network
  const float* cont_lo() const { return d_std() + L::N_CONT; }
  const float* cont_hi() const { return cont_lo() + L::N_CONT; }

  void load(const std::string& path) {
    std::ifstream f(path, std::ios::binary);
    if (!f) throw std::runtime_error("cannot open " + path);
    char magic[4]; uint32_t version; int dims[6]; float eps;
    f.read(magic, 4); f.read((char*)&version, 4); f.read((char*)dims, sizeof dims); f.read((char*)&eps, 4);
    if (!f || std::memcmp(magic, "NGEW", 4) != 0 || version != 1) throw std::runtime_error(path + ": not a NGEW v1 weights file");
    d = {dims[1], dims[0], dims[2], dims[4] + dims[5], dims[3], eps};
    if (d.S != L::STATE_DIM || d.M != L::MODEL_DIM || dims[4] != L::N_CONT || dims[5] != L::N_BIN)
      throw std::runtime_error(path + ": dimensions do not match layout.h (re-run python -m nge.export_onnx)");
    if (d.H % 32 != 0 || d.H > 1024) throw std::runtime_error(path + ": hidden size must be a multiple of 32 and <= 1024");
    blob.assign(NGE_DET_BLOB_SIZE(d.S, d.M, d.H, d.O, d.L) + 3 * L::N_CONT, 0.0f);
    auto rd = [&](float* dst, size_t n) { f.read((char*)dst, n * 4); if (!f) throw std::runtime_error(path + ": truncated"); };
    auto rd_T = [&](float* dstT, int out, int in) {        // file [out][in] -> blob [in][out]
      std::vector<float> tmp((size_t)out * in); rd(tmp.data(), tmp.size());
      for (int o = 0; o < out; ++o) for (int k = 0; k < in; ++k) dstT[(size_t)k * out + o] = tmp[(size_t)o * in + k];
    };
    float* b = blob.data();
    rd(b + off_s_mean(), d.S); rd(b + off_s_std(), d.S);
    rd_T(b + off_inp_w(), d.H, d.M); rd(b + off_inp_b(), d.H);
    for (int l = 0; l < d.L; ++l) {
      float* lw = b + off_layer(l);
      rd(lw + NGE_DET_LAYER_LN_W, d.H); rd(lw + NGE_DET_LAYER_LN_B(d.H), d.H);
      rd_T(lw + NGE_DET_LAYER_W1(d.H), d.H, d.H); rd(lw + NGE_DET_LAYER_B1(d.H), d.H);
      rd_T(lw + NGE_DET_LAYER_W2(d.H), d.H, d.H); rd(lw + NGE_DET_LAYER_B2(d.H), d.H);
    }
    rd_T(b + off_out_w(), d.O, d.H); rd(b + off_out_b(), d.O);
    rd(b + off_out_b() + d.O, 3 * L::N_CONT);           // d_std, cont_lo, cont_hi
    xs.resize(d.M); h.resize(d.H); a.resize(d.H); g.resize(d.H); y.resize(d.O);
  }

  // ---- CPU forward: identical op sequence to the kernel
  void forward_cpu(const float* x, bool scalar) {
    auto linear = scalar ? linear_scalar : linear_avx;
    const float* b = blob.data();
    for (int i = 0; i < d.M; ++i) xs[i] = i < d.S ? (x[i] - b[off_s_mean() + i]) / b[off_s_std() + i] : x[i];
    linear(b + off_inp_w(), d.M, d.H, xs.data(), b + off_inp_b(), h.data());
    for (int o = 0; o < d.H; ++o) h[o] = nge_det_silu(h[o]);
    for (int l = 0; l < d.L; ++l) {
      const float* lw = b + off_layer(l);
      float mean, inv;
      nge_det_ln_stats(h.data(), d.H, d.eps, &mean, &inv);
      for (int o = 0; o < d.H; ++o) a[o] = nge_det_ln_apply(h[o], mean, inv, lw[NGE_DET_LAYER_LN_W + o], lw[NGE_DET_LAYER_LN_B(d.H) + o]);
      linear(lw + NGE_DET_LAYER_W1(d.H), d.H, d.H, a.data(), lw + NGE_DET_LAYER_B1(d.H), g.data());
      for (int o = 0; o < d.H; ++o) g[o] = nge_det_silu(g[o]);
      linear(lw + NGE_DET_LAYER_W2(d.H), d.H, d.H, g.data(), lw + NGE_DET_LAYER_B2(d.H), a.data());
      for (int o = 0; o < d.H; ++o) h[o] = h[o] + a[o];
    }
    linear(b + off_out_w(), d.H, d.O, h.data(), b + off_out_b(), y.data());
  }

  // ---- CUDA
  static void ck(cu::CUresult r, const char* what) {
    if (r != 0) {
      const char* s = nullptr; cu::api().cuGetErrorString(r, &s);
      throw std::runtime_error(std::string(what) + ": " + (s ? s : "CUDA error"));
    }
  }

  void init_cuda() {
    const cu::Api& A = cu::api();
    if (!A.ok) throw std::runtime_error(A.error);
    ck(A.cuInit(0), "cuInit");
    ck(A.cuDeviceGet(&dev, 0), "cuDeviceGet");
    char nm[128] = {0}; A.cuDeviceGetName(nm, sizeof nm, dev); device_name = nm;
    int major = 0, minor = 0;
    ck(A.cuDeviceGetAttribute(&major, cu::ATTR_CC_MAJOR, dev), "cc major");
    ck(A.cuDeviceGetAttribute(&minor, cu::ATTR_CC_MINOR, dev), "cc minor");
    ck(A.cuDevicePrimaryCtxRetain(&ctx, dev), "cuDevicePrimaryCtxRetain");
    ck(A.cuCtxSetCurrent(ctx), "cuCtxSetCurrent");

    // pick the newest architecture NVRTC knows that the device can run; newer device than NVRTC -> PTX + driver JIT
    int n_arch = 0; A.nvrtcGetNumSupportedArchs(&n_arch);
    std::vector<int> archs((size_t)std::max(n_arch, 1)); A.nvrtcGetSupportedArchs(archs.data());
    const int cc = major * 10 + minor;
    int best = 0; for (int i = 0; i < n_arch; ++i) if (archs[i] <= cc && archs[i] > best) best = archs[i];
    if (!best) throw std::runtime_error("no NVRTC architecture fits compute capability " + std::to_string(cc));
    const bool cubin = best == cc;
    const std::string arch = std::string("--gpu-architecture=") + (cubin ? "sm_" : "compute_") + std::to_string(best);
    char def_s[32], def_m[32], def_h[32], def_o[32], def_l[32], def_eps[64];
    std::snprintf(def_s, sizeof def_s, "-DNGE_S=%d", d.S); std::snprintf(def_m, sizeof def_m, "-DNGE_M=%d", d.M);
    std::snprintf(def_h, sizeof def_h, "-DNGE_H=%d", d.H); std::snprintf(def_o, sizeof def_o, "-DNGE_O=%d", d.O);
    std::snprintf(def_l, sizeof def_l, "-DNGE_L=%d", d.L); std::snprintf(def_eps, sizeof def_eps, "-DNGE_EPS=%.9ef", d.eps);
    const char* opts[] = {arch.c_str(), "--std=c++17", "--fmad=false", "--ftz=false", "--prec-div=true", "--prec-sqrt=true",
                          def_s, def_m, def_h, def_o, def_l, def_eps};
    const char* hdrs[] = {nge_det_math_src};
    const char* hdr_names[] = {"nge/det_math.h"};
    cu::nvrtcProgram prog = nullptr;
    if (A.nvrtcCreateProgram(&prog, nge_det_kernel_src, "det_kernel.cu", 1, hdrs, hdr_names) != 0) throw std::runtime_error("nvrtcCreateProgram failed");
    const cu::nvrtcResult cr = A.nvrtcCompileProgram(prog, (int)(sizeof opts / sizeof *opts), opts);
    if (cr != 0) {
      size_t n = 0; A.nvrtcGetProgramLogSize(prog, &n); std::string log(n, '\0'); A.nvrtcGetProgramLog(prog, log.data());
      A.nvrtcDestroyProgram(&prog);
      throw std::runtime_error(std::string("NVRTC: ") + A.nvrtcGetErrorString(cr) + "\n" + log);
    }
    size_t n = 0; std::vector<char> image;
    if (cubin) { A.nvrtcGetCUBINSize(prog, &n); image.resize(n); A.nvrtcGetCUBIN(prog, image.data()); }
    else { A.nvrtcGetPTXSize(prog, &n); image.resize(n); A.nvrtcGetPTX(prog, image.data()); }
    A.nvrtcDestroyProgram(&prog);
    ck(A.cuModuleLoadData(&mod, image.data()), "cuModuleLoadData");
    ck(A.cuModuleGetFunction(&fn, mod, "nge_det_step"), "cuModuleGetFunction");
    ck(A.cuMemAlloc(&d_w, blob.size() * 4), "cuMemAlloc weights");
    ck(A.cuMemAlloc(&d_x, (size_t)d.M * 4), "cuMemAlloc x");
    ck(A.cuMemAlloc(&d_y, (size_t)d.O * 4), "cuMemAlloc y");
    ck(A.cuMemcpyHtoD(d_w, blob.data(), blob.size() * 4), "upload weights");
    int nv_major = 0, nv_minor = 0; A.nvrtcVersion(&nv_major, &nv_minor);
    std::printf("[det] cuda kernel for %s (sm_%d, %s via NVRTC %d.%d)\n", device_name.c_str(), cc, cubin ? "cubin" : "ptx", nv_major, nv_minor);
  }

  void forward_cuda(const float* x) {
    const cu::Api& A = cu::api();
    ck(A.cuCtxSetCurrent(ctx), "cuCtxSetCurrent");
    ck(A.cuMemcpyHtoD(d_x, x, (size_t)d.M * 4), "upload x");
    void* params[] = {&d_x, &d_w, &d_y};
    ck(A.cuLaunchKernel(fn, 1, 1, 1, (unsigned)d.H, 1, 1, 0, nullptr, params, nullptr), "cuLaunchKernel");
    ck(A.cuMemcpyDtoH(y.data(), d_y, (size_t)d.O * 4), "download y");
  }

  void release_cuda() {
    const cu::Api& A = cu::api();
    if (!A.ok) return;
    if (d_w) A.cuMemFree(d_w);
    if (d_x) A.cuMemFree(d_x);
    if (d_y) A.cuMemFree(d_y);
    if (mod) A.cuModuleUnload(mod);
    if (ctx) A.cuDevicePrimaryCtxRelease(dev);
    d_w = d_x = d_y = 0; mod = nullptr; ctx = nullptr;
  }

  // ---- post-processing (host, shared by all backends): threshold, clamp, zero inactive bullets, consume inputs
  ModelVector finish(const ModelVector& x) const {
    ModelVector out{};
    State& n = state_of(out);
    n = state_of(x);
    for (int j = 0; j < L::N_CONT; ++j) {
      const int idx = L::CONT_IDX[j];
      const float v = fmaf(y[j], d_std()[j], n[idx]);
      n[idx] = v < cont_lo()[j] ? cont_lo()[j] : (v > cont_hi()[j] ? cont_hi()[j] : v);
    }
    for (int j = 0; j < L::N_BIN; ++j) n[L::BIN_IDX[j]] = y[L::N_CONT + j] > 0.0f ? 1.0f : 0.0f;
    for (int p = 0; p < L::N_PLAYERS; ++p)
      for (int b = 0; b < L::N_BULLETS; ++b)
        if (bullet(n, p, b, 2) == 0.0f) { bullet(n, p, b, 0) = 0.0f; bullet(n, p, b, 1) = 0.0f; }
    return out;
  }
};

bool DetSim::cpu_supported() {
#ifdef _WIN32
  int r[4]; __cpuid(r, 1);
  const bool fma = (r[2] >> 12) & 1;
  __cpuidex(r, 7, 0);
  const bool avx2 = (r[1] >> 5) & 1;
  return fma && avx2;
#else
  return __builtin_cpu_supports("avx2") && __builtin_cpu_supports("fma");
#endif
}

bool DetSim::cuda_available(std::string* why) {
  const cu::Api& A = cu::api();
  if (!A.ok) { if (why) *why = A.error; return false; }
  cu::CUresult r = A.cuInit(0);
  if (r != 0) { if (why) { const char* s = nullptr; A.cuGetErrorString(r, &s); *why = s ? s : "cuInit failed"; } return false; }
  int dummy = 0;
  if (A.cuDeviceGet(&dummy, 0) != 0) { if (why) *why = "no CUDA device"; return false; }
  return true;
}

DetSim::DetSim(const std::string& nge_path, Backend want) : impl_(std::make_unique<Impl>()) {
  impl_->load(nge_path);
  if (!cpu_supported()) throw std::runtime_error("the deterministic world model needs a CPU with AVX2 and FMA");
  impl_->backend = want;
  if (want == Backend::Cuda) {
    try { impl_->init_cuda(); }
    catch (const std::exception& e) {
      std::fprintf(stderr, "[det] CUDA unavailable (%s); using the CPU\n", e.what());
      impl_->release_cuda();
      impl_->backend = Backend::Cpu;
    }
  }
  name_ = impl_->backend == Backend::Cuda ? "det(cuda)" : impl_->backend == Backend::CpuScalar ? "det(cpu-scalar)" : "det(cpu)";
}

DetSim::~DetSim() { if (impl_) impl_->release_cuda(); }

DetSim::Backend DetSim::backend() const { return impl_->backend; }

ModelVector DetSim::step(const ModelVector& x) {
  const auto t0 = std::chrono::steady_clock::now();
  switch (impl_->backend) {
    case Backend::Cuda: impl_->forward_cuda(x.data()); break;
    case Backend::CpuScalar: impl_->forward_cpu(x.data(), true); break;
    default: impl_->forward_cpu(x.data(), false); break;
  }
  ModelVector out = impl_->finish(x);
  last_ms_ = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
  return out;
}

