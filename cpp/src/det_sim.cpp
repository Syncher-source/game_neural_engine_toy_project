struct Dims { int S, M, H, O, L; float eps; };

// Same arithmetic as nge_det_linear: lane j computes output o+j with fmaf(w, x, acc) from the
// bias in ascending k. Four vectors in flight hide the FMA latency.
void linear_avx(const float* wT, int n_in, int n_out, const float* x, const float* bias, float* out) {
  int o = 0;
  for (; o + 32 <= n_out; o += 32) {
    __m256 a0 = _mm256_loadu_ps(bias + o), a1 = _mm256_loadu_ps(bias + o + 8), a2 = _mm256_loadu_ps(bias + o + 16), a3 = _mm256_loadu_ps(bias + o + 24);
    for (int k = 0; k < n_in; ++k) {
      const __m256 xk = _mm256_set1_ps(x[k]);
      const float* row = wT + (size_t)k * n_out + o;
      a0 = _mm256_fmadd_ps(_mm256_loadu_ps(row), xk, a0);
      a1 = _mm256_fmadd_ps(_mm256_loadu_ps(row + 8), xk, a1);
      a2 = _mm256_fmadd_ps(_mm256_loadu_ps(row + 16), xk, a2);
      a3 = _mm256_fmadd_ps(_mm256_loadu_ps(row + 24), xk, a3);
    }
    _mm256_storeu_ps(out + o, a0); _mm256_storeu_ps(out + o + 8, a1); _mm256_storeu_ps(out + o + 16, a2); _mm256_storeu_ps(out + o + 24, a3);
  }
  for (; o + 8 <= n_out; o += 8) {
    __m256 a0 = _mm256_loadu_ps(bias + o);
    for (int k = 0; k < n_in; ++k) a0 = _mm256_fmadd_ps(_mm256_loadu_ps(wT + (size_t)k * n_out + o), _mm256_set1_ps(x[k]), a0);
    _mm256_storeu_ps(out + o, a0);
  }
  for (; o < n_out; ++o) out[o] = nge_det_linear(wT, n_in, n_out, o, x, bias[o]);
}

void linear_scalar(const float* wT, int n_in, int n_out, const float* x, const float* bias, float* out) {
  for (int o = 0; o < n_out; ++o) out[o] = nge_det_linear(wT, n_in, n_out, o, x, bias[o]);
}

