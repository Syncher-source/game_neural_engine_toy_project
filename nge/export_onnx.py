"""Export the trained world model for the C++ runtime.

    python -m nge.export_onnx --ckpt checkpoints/world_model.pt

Produces
  checkpoints/world_model.onnx     full next-state graph (post-processing baked in)
  checkpoints/test_vectors.bin     (state, input, classic_next, neural_next) rows for
                                   the C++ cross-check test
  cpp/include/nge/layout.h         state layout + physics constants as C++ constexprs

The ONNX graph takes  state (B, STATE_DIM) float32, input (B, INPUT_DIM) float32
and returns next_state (B, STATE_DIM) float32.  Thresholding, clamping and
zeroing of inactive bullets are expressed with constant matrices so the graph
stays plain ONNX (MatMul/Add/Greater/Min/Max) with no scatter ops.
"""
from __future__ import annotations

import argparse
import struct
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn

from . import config as C
from . import sim
from . import state as S
from .model import load_model, WorldModel, N_BUL, FORM_DIR_IDX


class ExportModel(nn.Module):
    def __init__(self, m):
        super().__init__()
        self.m = m
        P_cont = torch.zeros(S.N_CONT, S.STATE_DIM)
        P_cont[torch.arange(S.N_CONT), torch.as_tensor(S.CONT_IDX)] = 1.0
        P_act = torch.zeros(N_BUL, S.STATE_DIM); P_act[torch.arange(N_BUL), torch.as_tensor(S.BUL_ACT_IDX)] = 1.0
        P_dir = torch.zeros(1, S.STATE_DIM); P_dir[0, FORM_DIR_IDX] = 1.0
        P_inv = torch.zeros(C.N_INVADERS, S.STATE_DIM); P_inv[torch.arange(C.N_INVADERS), S.INV_OFF + torch.arange(C.N_INVADERS)] = 1.0
        lo = torch.full((S.STATE_DIM,), -1e9); hi = torch.full((S.STATE_DIM,), 1e9)
        lo[S.CONT_IDX] = torch.as_tensor(S.CONT_LO[S.CONT_IDX]); hi[S.CONT_IDX] = torch.as_tensor(S.CONT_HI[S.CONT_IDX])
        M_bul = torch.zeros(C.N_PLAYERS * C.N_BULLETS, S.STATE_DIM)
        for b, (ix, iy) in enumerate(S.BUL_POS_IDX.reshape(-1, 2)):
            M_bul[b, int(ix)] = 1.0; M_bul[b, int(iy)] = 1.0
        self.register_buffer("P_cont", P_cont); self.register_buffer("P_act", P_act); self.register_buffer("P_dir", P_dir); self.register_buffer("P_inv", P_inv)
        self.register_buffer("lo", lo); self.register_buffer("hi", hi); self.register_buffer("M_bul", M_bul)

    def forward(self, x):
        """x: (B, MODEL_DIM) = [state | inputs] -> x_next (B, MODEL_DIM) = [next state | zeros].
        Same vector type in and out; the input slots come back consumed."""
        state = x[:, : S.STATE_DIM]
        d, logits = self.m(x)
        cont_next = state @ self.P_cont.t() + d * self.m.d_std
        act, dir_next, alive_next, _ = WorldModel.events(state, logits)      # one bullet, one kill: inside the graph
        nxt = cont_next @ self.P_cont + act @ self.P_act + dir_next[:, None] @ self.P_dir + alive_next @ self.P_inv
        nxt = torch.minimum(torch.maximum(nxt, self.lo), self.hi)
        keep = 1.0 - (1.0 - act) @ self.M_bul
        consumed = x[:, S.STATE_DIM:] * 0.0
        return torch.cat([nxt * keep, consumed], dim=1)


def flit(v):
    t = f"{float(v):.9g}"
    return t + ("f" if ("." in t or "e" in t or "n" in t) else ".0f")


def write_layout_header(path: Path):
    def arr(name, vals, typ="int"):
        return f"inline constexpr {typ} {name}[{len(vals)}] = {{{', '.join(str(v) for v in vals)}}};"
    def farr(name, vals):
        return f"inline constexpr float {name}[{len(vals)}] = {{{', '.join(flit(v) for v in vals)}}};"
    lines = [
        "// GENERATED by `python -m nge.export_onnx` from nge/config.py and nge/state.py. Do not edit.",
        "#pragma once", "namespace nge::L {",
        f"inline constexpr int TICK_RATE = {C.TICK_RATE};",
        f"inline constexpr float DT = {flit(C.DT)};",
        f"inline constexpr int N_PLAYERS = {C.N_PLAYERS};",
        f"inline constexpr int N_BULLETS = {C.N_BULLETS};",
        f"inline constexpr int INV_COLS = {C.INV_COLS};",
        f"inline constexpr int INV_ROWS = {C.INV_ROWS};",
        f"inline constexpr int N_INVADERS = {C.N_INVADERS};",
        f"inline constexpr int SHIP_OFF = {S.SHIP_OFF};",
        f"inline constexpr int SHIP_STRIDE = {S.SHIP_STRIDE};",
        f"inline constexpr int BUL_OFF = {S.BUL_OFF};",
        f"inline constexpr int BUL_STRIDE = {S.BUL_STRIDE};",
        f"inline constexpr int FORM_OFF = {S.FORM_OFF};",
        f"inline constexpr int INV_OFF = {S.INV_OFF};",
        f"inline constexpr int STATE_DIM = {S.STATE_DIM};",
        f"inline constexpr int INPUT_STRIDE = {S.INPUT_STRIDE};",
        f"inline constexpr int INPUT_DIM = {S.INPUT_DIM};",
        f"inline constexpr int MODEL_DIM = {S.MODEL_DIM};   // [state | inputs]: the single vector a model receives",
        f"inline constexpr int N_CONT = {S.N_CONT};",
        f"inline constexpr int N_BIN = {S.N_BIN};",
        arr("CONT_IDX", S.CONT_IDX.tolist()), arr("BIN_IDX", S.BIN_IDX.tolist()),
        farr("CONT_LO", S.CONT_LO.tolist()), farr("CONT_HI", S.CONT_HI.tolist()),
        "// physics",
    ]
    for k in ["SHIP_RADIUS", "SHIP_ACCEL", "SHIP_DAMPING", "SHIP_MAX_SPEED", "SHIP_X_MIN", "SHIP_X_MAX", "SHIP_Y_MIN", "SHIP_Y_MAX",
              "BULLET_SPEED", "FIRE_COOLDOWN_DECAY", "INV_X0", "INV_Y0", "INV_DX", "INV_DY", "INV_HALF_W", "INV_HALF_H",
              "FORM_SPEED", "FORM_OX_MAX", "FORM_STEP_DOWN", "FORM_OY_MAX"]:
        lines.append(f"inline constexpr float {k} = {flit(getattr(C, k))};")
    lines.append("}  // namespace nge::L")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="checkpoints/world_model.pt")
    ap.add_argument("--onnx", default="checkpoints/world_model.onnx")
    ap.add_argument("--vectors", default="checkpoints/test_vectors.bin")
    ap.add_argument("--header", default="cpp/include/nge/layout.h")
    ap.add_argument("--n-vectors", type=int, default=2048)
    ap.add_argument("--renderer", default="checkpoints/renderer.pt", help="renderer checkpoint ('' to skip)")
    ap.add_argument("--renderer-onnx", default="checkpoints/renderer.onnx")
    ap.add_argument("--renderer-vectors", default="checkpoints/renderer_test.bin")
    ap.add_argument("--render-res", type=int, default=0, help="export the renderer at this resolution (0 = as trained)")
    args = ap.parse_args()

    m = load_model(args.ckpt, "cpu")
    em = ExportModel(m).eval()
    rng = np.random.default_rng(42)
    st = S.random_state(args.n_vectors, rng)
    st[: args.n_vectors // 4] = S.initial_state(args.n_vectors // 4)
    ut = rng.uniform(-1, 1, (args.n_vectors, S.INPUT_DIM)).astype(np.float32)
    ut[:, 2::3] = (rng.random((args.n_vectors, C.N_PLAYERS)) < 0.5).astype(np.float32)
    ut[::2, 0:2] = np.round(ut[::2, 0:2])    # some discrete stick values too

    xt = torch.as_tensor(S.pack(st, ut))
    with torch.no_grad():
        ref = m.predict(xt).numpy()
        exp = em(xt).numpy()
    print(f"export graph vs model.predict: max abs diff {np.abs(ref - exp).max():.2e}")

    torch.onnx.export(em, (xt[:1],), args.onnx, opset_version=17,
                      input_names=["x"], output_names=["x_next"],
                      dynamic_axes={"x": {0: "batch"}, "x_next": {0: "batch"}}, dynamo=False)
    import onnxruntime as ort
    sess = ort.InferenceSession(args.onnx, providers=["CPUExecutionProvider"])
    out = sess.run(["x_next"], {"x": S.pack(st, ut)})[0]
    assert out.shape[1] == S.MODEL_DIM and np.all(out[:, S.STATE_DIM:] == 0), "input slots must come back consumed"
    print(f"onnxruntime vs torch: max abs diff {np.abs(out - exp).max():.2e}   saved {args.onnx} (x[{S.MODEL_DIM}] -> x_next[{S.MODEL_DIM}], inputs consumed)")
    out = out[:, : S.STATE_DIM]

    classic = sim.step(st, ut)
    with open(args.vectors, "wb") as f:
        f.write(struct.pack("<3i", args.n_vectors, S.STATE_DIM, S.INPUT_DIM))
        for a in (st, ut, classic, out):
            f.write(np.ascontiguousarray(a, dtype="<f4").tobytes())
    print(f"saved {args.vectors} ({args.n_vectors} rows)")
    write_layout_header(Path(args.header))
    print(f"saved {args.header}")
    from .export_det import export_det
    det_path = str(Path(args.onnx).with_suffix(".nge"))
    print(f"saved {det_path} ({export_det(m, det_path) / 1e6:.1f} MB, raw weights for the deterministic C++ kernel)")

    if args.renderer and Path(args.renderer).exists():
        export_renderer(args.renderer, args.renderer_onnx, args.renderer_vectors, st[:8], args.render_res)
    elif args.renderer:
        print(f"renderer checkpoint {args.renderer} not found, skipping (train with python -m nge.train_renderer)")


class ExportRenderer(nn.Module):
    """Renderer with the display conversion baked in: output is uint8 RGBA (B, H, W, 4).

    Doing the float -> byte conversion inside the graph means the C++ client can hand the
    output buffer straight to a GPU texture (no CUDA kernel of its own, no CPU readback).
    """

    def __init__(self, r):
        super().__init__()
        self.r = r

    def forward(self, x):
        """x: (B, MODEL_DIM). Only the state part is read; the input slots are sliced away, so
        whatever they contain cannot influence the frame."""
        state = x[:, : S.STATE_DIM]
        img = self.r(state)                                        # (B, H, W, 3) in [0, 1]
        alpha = torch.ones_like(img[..., :1])
        rgba = torch.cat([img, alpha], dim=-1) * 255.0 + 0.5
        return torch.clamp(torch.floor(rgba), 0.0, 255.0).to(torch.uint8)


def export_renderer(ckpt: str, onnx_path: str, vectors_path: str, states: np.ndarray, res: int) -> None:
    from .renderer import load_renderer
    r = load_renderer(ckpt, "cpu")
    if res:
        r = r.at_resolution(res, res)
    er = ExportRenderer(r).eval()
    rng = np.random.default_rng(7)
    junk = rng.uniform(-1, 1, (len(states), S.INPUT_DIM)).astype(np.float32)      # arbitrary input slots
    xs = S.pack(states, junk)
    with torch.no_grad():
        ref = er(torch.as_tensor(xs)).numpy()
        ref_zero = er(torch.as_tensor(S.pack(states, np.zeros_like(junk)))).numpy()
    assert np.array_equal(ref, ref_zero), "renderer must ignore the input slots"
    # Static batch of 1: the client renders one frame per tick, and a fixed shape lets the
    # exporter constant-fold the broadcast/shape logic so every node runs on the GPU provider.
    torch.onnx.export(er, (torch.as_tensor(xs[:1]),), onnx_path, opset_version=17, input_names=["x"], output_names=["image"],
                      do_constant_folding=True, dynamo=False)
    import onnx
    m = onnx.load(onnx_path)
    dims = m.graph.output[0].type.tensor_type.shape.dim
    for d, v in zip(dims, [1, r.H, r.W, 4]):
        d.ClearField("dim_param"); d.dim_value = v
    onnx.save(m, onnx_path)
    shape_ops = sorted({n.op_type for n in m.graph.node if n.op_type in ("Shape", "ConstantOfShape", "Expand", "Where", "Equal", "Gather", "Reshape")})
    print(f"renderer graph: {len(m.graph.node)} nodes, shape-related ops left: {shape_ops or 'none'}")
    import onnxruntime as ort
    sess = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
    out = np.concatenate([sess.run(["image"], {"x": xs[i:i + 1]})[0] for i in range(len(states))])
    assert out.dtype == np.uint8 and out.shape[-1] == 4, out.shape
    diff = np.abs(out.astype(np.int16) - ref.astype(np.int16))
    print(f"renderer {r.H}x{r.W} RGBA8: onnxruntime vs torch max diff {diff.max()} (values off by >1: {(diff > 1).sum()})   saved {onnx_path}")
    with open(vectors_path, "wb") as f:     # rows are full model vectors with junk in the input slots
        f.write(struct.pack("<4i", len(states), S.MODEL_DIM, r.H, r.W))
        f.write(np.ascontiguousarray(xs, dtype="<f4").tobytes())
        f.write(np.ascontiguousarray(out).tobytes())
    print(f"saved {vectors_path} ({len(states)} RGBA frames)")


if __name__ == "__main__":
    main()
